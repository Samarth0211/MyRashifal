'use client';

import html2canvas from 'html2canvas';
import { jsPDF } from 'jspdf';

export async function generateKundliPDF(dashboardRef, birthDetails) {
  if (!dashboardRef?.current) throw new Error('Dashboard ref not available');

  const element = dashboardRef.current;

  // Capture the full dashboard
  const canvas = await html2canvas(element, {
    scale: 2,
    useCORS: true,
    backgroundColor: '#0a0a1a', // Match dark bg
    logging: false,
    windowWidth: 1200,
  });

  const imgWidth = 210; // A4 width in mm
  const pageHeight = 297; // A4 height in mm
  const imgHeight = (canvas.height * imgWidth) / canvas.width;

  const pdf = new jsPDF('p', 'mm', 'a4');

  // Add header
  pdf.setFillColor(10, 10, 26); // bg-primary
  pdf.rect(0, 0, 210, 20, 'F');
  pdf.setFontSize(16);
  pdf.setTextColor(212, 175, 55); // gold
  pdf.text('MyRashifal+ — Vedic Birth Chart', 105, 12, { align: 'center' });

  // Add birth details
  pdf.setFontSize(10);
  pdf.setTextColor(180, 180, 200);
  const name = birthDetails?.name || 'Unknown';
  const dob = birthDetails?.dob || '';
  const tob = birthDetails?.tob || '';
  const pob = birthDetails?.pob || '';
  pdf.text(`${name}  |  ${dob}  |  ${tob}  |  ${pob}`, 105, 25, { align: 'center' });

  // Add the captured image below the header, paginated
  const startY = 30;
  let position = startY;
  const imgData = canvas.toDataURL('image/jpeg', 0.85);

  // First page
  const remainingOnFirst = pageHeight - startY - 10;
  if (imgHeight <= remainingOnFirst) {
    // Fits on one page
    pdf.addImage(imgData, 'JPEG', 0, startY, imgWidth, imgHeight);
  } else {
    // Multi-page
    let heightLeft = imgHeight;
    let sourceY = 0;

    // First page portion
    const firstPagePortion = remainingOnFirst;
    pdf.addImage(imgData, 'JPEG', 0, startY, imgWidth, imgHeight);

    heightLeft -= firstPagePortion;
    sourceY = firstPagePortion;

    while (heightLeft > 0) {
      pdf.addPage();
      // Offset negative to show the next portion
      pdf.addImage(imgData, 'JPEG', 0, -sourceY, imgWidth, imgHeight);
      heightLeft -= pageHeight;
      sourceY += pageHeight;
    }
  }

  // Add footer on last page
  const totalPages = pdf.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setFontSize(8);
    pdf.setTextColor(120, 120, 140);
    pdf.text(`Generated by MyRashifal+ (myrashifal.in)  |  Page ${i} of ${totalPages}`, 105, 290, { align: 'center' });
  }

  // Download
  const fileName = `${name.replace(/\s+/g, '_')}_Kundli_MyRashifal.pdf`;
  pdf.save(fileName);
}
